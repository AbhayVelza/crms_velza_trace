"use client";

// Guided print order wizard (spec 6.2). Every question is a step with Back/Next.
// The summary comes from the server (lib/core planPrintOrder); the UI holds no business rules.

import { useRouter } from "next/navigation";
import { useState, type ReactNode } from "react";
import { useSession } from "@/components/session";
import { GeneratedCodes } from "@/components/GeneratedCodes";
import { IconArrowLeft, IconArrowRight, IconCheck, IconMinus, IconPlus, IconPrinter } from "@/components/icons";
import { Button, Card, Code, cx, Field, Input, Loading, Notice, PageTitle, Table, Td } from "@/components/ui";
import { api, errorText } from "@/lib/client";
import type { BatchInput, PrintOrderPlan } from "@/lib/core/printOrder";
import type { PrintOrder } from "@/lib/core/types";
import { notifyDataChanged } from "@/lib/events";

const STEPS = ["How many batches?", "Flavour", "Dates", "Cases", "Trays", "Summary", "Print"] as const;

function isoDate(d: Date) {
  return d.toISOString().slice(0, 10);
}

function newBatch(): BatchInput {
  const today = new Date();
  const expiry = new Date(today);
  expiry.setFullYear(expiry.getFullYear() + 1);
  return { flavour: "", mfgDate: isoDate(today), expiryDate: isoDate(expiry), cases: 0, trays: 0 };
}

function CountInput({ value, onChange, label }: { value: number; onChange: (n: number) => void; label: string }) {
  return (
    <div className="flex items-center gap-2">
      <Button variant="secondary" aria-label={`Decrease ${label}`} className="w-10 px-0" onClick={() => onChange(Math.max(0, value - 1))}>
        <IconMinus size={16} />
      </Button>
      <Input
        type="number"
        inputMode="numeric"
        min={0}
        aria-label={label}
        className="w-28 text-center text-lg font-semibold tabular"
        value={Number.isNaN(value) ? "" : value}
        onChange={(e) => onChange(e.target.value === "" ? NaN : Number(e.target.value))}
      />
      <Button variant="secondary" aria-label={`Increase ${label}`} className="w-10 px-0" onClick={() => onChange((Number.isNaN(value) ? 0 : value) + 1)}>
        <IconPlus size={16} />
      </Button>
    </div>
  );
}

export default function NewPrintOrderPage() {
  const { data, flavourName } = useSession();
  const router = useRouter();
  const [step, setStep] = useState(0);
  const [count, setCount] = useState(1);
  const [batches, setBatches] = useState<BatchInput[]>([newBatch()]);
  const [plan, setPlan] = useState<PrintOrderPlan | null>(null);
  const [offline, setOffline] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [created, setCreated] = useState<PrintOrder | null>(null);

  const flavours = (data?.flavours ?? []).filter((f) => f.active);
  const update = (i: number, patch: Partial<BatchInput>) => setBatches((bs) => bs.map((b, j) => (j === i ? { ...b, ...patch } : b)));

  async function loadPreview() {
    setBusy(true);
    setError(null);
    try {
      const r = await api<{ plan: PrintOrderPlan; device: { offline: boolean } }>("/api/print-orders", { body: { batches, preview: true } });
      setPlan(r.plan);
      setOffline(r.device.offline);
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  async function next() {
    setError(null);
    if (step === 0) {
      const n = Math.floor(count);
      if (!(n >= 1 && n <= 20)) return setError("Enter between 1 and 20 batches");
      setBatches((bs) => Array.from({ length: n }, (_, i) => bs[i] ?? newBatch()));
    }
    if (step === 1 && batches.some((b) => !b.flavour)) return setError("Choose a flavour for every batch");
    if (step === 4) await loadPreview();
    setStep((s) => Math.min(s + 1, STEPS.length - 1));
  }

  async function create() {
    setBusy(true);
    setError(null);
    try {
      const r = await api<{ printOrder: PrintOrder }>("/api/print-orders", { body: { batches } });
      setCreated(r.printOrder);
      notifyDataChanged();
      setStep(6);
    } catch (e) {
      setError(errorText(e));
      await loadPreview();
    } finally {
      setBusy(false);
    }
  }

  function restart() {
    setStep(0);
    setCount(1);
    setBatches([newBatch()]);
    setPlan(null);
    setCreated(null);
    setError(null);
  }

  const perBatch = (render: (b: BatchInput, i: number) => ReactNode) => (
    <div className="space-y-3">
      {batches.map((b, i) => (
        <div key={i} className="rounded-md border border-line bg-surface-2 p-3 sm:p-4">
          <div className="mb-2.5 text-sm font-bold text-foreground">
            Batch {i + 1}
            {b.flavour && <span className="font-normal text-muted-foreground"> · {flavourName(b.flavour)}</span>}
          </div>
          {render(b, i)}
        </div>
      ))}
    </div>
  );

  return (
    <>
      <PageTitle title="New print order" subtitle="Answer each question; batch codes and lot numbers are generated by the system." />
      <ol className="mb-5 flex flex-wrap items-center gap-x-1 gap-y-2 text-xs" aria-label="Steps">
        {STEPS.map((s, i) => (
          <li key={s} aria-current={i === step ? "step" : undefined} className="flex items-center gap-1">
            <span
              className={cx(
                "inline-flex items-center gap-2 rounded-full border py-1 pl-1 pr-3 transition-colors duration-200",
                i === step ? "border-primary bg-primary font-semibold text-primary-foreground" : i < step ? "border-line-strong bg-surface text-foreground" : "border-line bg-transparent text-muted-foreground",
              )}
            >
              <span
                className={cx(
                  "inline-flex h-5 w-5 items-center justify-center rounded-full text-[0.6875rem] font-bold",
                  i === step ? "bg-primary-foreground text-primary" : i < step ? "bg-foreground text-background" : "bg-muted text-muted-foreground",
                )}
              >
                {i < step ? <IconCheck size={12} strokeWidth={2.5} /> : i + 1}
              </span>
              {s}
            </span>
            {i < STEPS.length - 1 && <span aria-hidden="true" className="h-px w-3 bg-line-strong" />}
          </li>
        ))}
      </ol>

      <Card>
        {step === 0 && (
          <Field label="How many batches do you want to create?" hint="One batch = one flavour with one manufacture date; it gets its own random batch code.">
            <CountInput label="Number of batches" value={count} onChange={setCount} />
          </Field>
        )}

        {step === 1 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Which flavour?</h2>
            {perBatch((b, i) => (
              <div className="flex flex-wrap gap-2">
                {flavours.map((f) => (
                  <button
                    key={f.code}
                    type="button"
                    onClick={() => update(i, { flavour: f.code })}
                    aria-pressed={b.flavour === f.code}
                    className={b.flavour === f.code ? "inline-flex min-h-10 items-center gap-2 rounded-full border-2 border-primary bg-primary px-4 font-semibold text-primary-foreground transition-colors duration-150 [&_span]:text-primary-foreground/70" : "inline-flex min-h-10 items-center gap-2 rounded-full border border-line-strong bg-surface px-4 text-foreground-2 transition-colors duration-150 hover:border-foreground hover:text-foreground"}
                  >
                    {f.name} <span className="font-mono text-xs text-muted-foreground">{f.code}</span>
                  </button>
                ))}
              </div>
            ))}
          </>
        )}

        {step === 2 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Manufacture and expiry dates</h2>
            {perBatch((b, i) => (
              <div className="grid gap-3 sm:grid-cols-2">
                <Field label="Manufacture date">
                  <Input type="date" aria-label={`Batch ${i + 1} manufacture date`} value={b.mfgDate} onChange={(e) => update(i, { mfgDate: e.target.value })} />
                </Field>
                <Field label="Expiry date">
                  <Input type="date" aria-label={`Batch ${i + 1} expiry date`} value={b.expiryDate} onChange={(e) => update(i, { expiryDate: e.target.value })} />
                </Field>
              </div>
            ))}
          </>
        )}

        {step === 3 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">How many Cases (4 packs × 6 cans)?</h2>
            {perBatch((b, i) => (
              <CountInput label={`Batch ${i + 1} cases`} value={b.cases} onChange={(n) => update(i, { cases: n })} />
            ))}
          </>
        )}

        {step === 4 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">How many Trays (6 packs × 4 cans)?</h2>
            {perBatch((b, i) => (
              <CountInput label={`Batch ${i + 1} trays`} value={b.trays} onChange={(n) => update(i, { trays: n })} />
            ))}
          </>
        )}

        {step === 5 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Summary</h2>
            {offline && (
              <Notice tone="warn" className="mb-3">
                Device is offline: batch codes come from the reserved pool and the order will be saved unsynced (it can be printed and verified, but not dispatched until synced).
              </Notice>
            )}
            {plan ? (
              <>
                <Table head={["Batch", "Batch code", "Flavour", "Dates", "Cases", "Trays", "Lots (hex)", "Stickers"]}>
                  {plan.batches.map((b) => (
                    <tr key={b.index} data-testid={`summary-batch-${b.index + 1}`}>
                      <Td>{b.index + 1}</Td>
                      <Td>{b.batchCode ? <Code>{b.batchCode}</Code> : <span className="text-danger">none</span>}</Td>
                      <Td>{flavourName(b.flavour) || "—"}</Td>
                      <Td className="whitespace-nowrap text-xs">
                        {b.mfgDate} → {b.expiryDate}
                      </Td>
                      <Td>
                        {b.cases}
                        {b.caseRange && <div className="font-mono text-xs text-muted-foreground">{b.caseRange.join("–")}</div>}
                      </Td>
                      <Td>
                        {b.trays}
                        {b.trayRange && <div className="font-mono text-xs text-muted-foreground">{b.trayRange.join("–")}</div>}
                      </Td>
                      <Td>{b.lotRange ? <Code>{b.lotRange[0] === b.lotRange[1] ? b.lotRange[0] : b.lotRange.join("–")}</Code> : "—"}</Td>
                      <Td>
                        <span data-testid={`summary-stickers-${b.index + 1}`}>{b.stickerCount}</span>
                        <div className="text-xs text-muted-foreground">
                          {b.cases}×5 + {b.trays}×7
                        </div>
                      </Td>
                    </tr>
                  ))}
                  <tr className="bg-surface-2 font-semibold">
                    <Td>Total</Td>
                    <Td />
                    <Td />
                    <Td />
                    <Td>{plan.batches.reduce((s, b) => s + (b.cases || 0), 0)}</Td>
                    <Td>{plan.batches.reduce((s, b) => s + (b.trays || 0), 0)}</Td>
                    <Td>{plan.totalLots} lots</Td>
                    <Td>
                      <span data-testid="summary-total-stickers">{plan.totalStickers}</span>
                    </Td>
                  </tr>
                </Table>
                {plan.errors.length > 0 && (
                  <Notice tone="error" className="mt-3">
                    <ul className="list-disc pl-5">
                      {plan.errors.map((e, i) => (
                        <li key={i}>{e.message}</li>
                      ))}
                    </ul>
                  </Notice>
                )}
              </>
            ) : (
              <Loading>Calculating…</Loading>
            )}
          </>
        )}

        {step === 6 && created && (
          <div className="space-y-3">
            <Notice tone="ok">
              Print order created: {created.stickerCount} stickers for batch{created.batchCodes.length > 1 ? "es" : ""} {created.batchCodes.join(", ")}
              {!created.synced && " (offline — unsynced)"}.
            </Notice>
            <div className="flex flex-wrap gap-2">
              <Button onClick={() => router.push(`/print/${created.id}`)}>
                <IconPrinter size={17} />
                Open print view
              </Button>
              <Button variant="secondary" onClick={restart}>
                New print order
              </Button>
            </div>
            <GeneratedCodes printOrderId={created.id} />
          </div>
        )}

        {error && (
          <Notice tone="error" className="mt-3">
            {error}
          </Notice>
        )}

        {step < 6 && (
          <div className="mt-5 flex justify-between gap-2 border-t border-line pt-4">
            <Button variant="secondary" onClick={() => setStep((s) => Math.max(0, s - 1))} disabled={step === 0 || busy}>
              <IconArrowLeft size={17} />
              Back
            </Button>
            {step < 5 ? (
              <Button onClick={next} loading={busy}>
                Next
                <IconArrowRight size={17} />
              </Button>
            ) : (
              <Button onClick={create} loading={busy} disabled={!plan?.ok}>
                <IconPrinter size={17} />
                Create &amp; print
              </Button>
            )}
          </div>
        )}
      </Card>
    </>
  );
}
