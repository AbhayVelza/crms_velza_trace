const STEPS = ["How many batches?", "Flavour", "Dates", "Cases", "Trays", "Summary", "Print"] as const;

function isoDate(d: Date) {
  return d.toISOString().slice(0, 10);
}

function newBatch(): BatchInput {
  const today = new Date();
  const expiry = new Date(today);
  expiry.setFullYear(expiry.getFullYear() + 1);
  return { flavour: "", mfgDate: isoDate(today), expiryDate: isoDate(expiry), cases: 0, trays: 0 };
}

function CountInput({ value, onChange, label }: { value: number; onChange: (n: number) => void; label: string }) {
  return (
    <div className="flex items-center gap-2">
      <Button variant="secondary" aria-label={`Decrease ${label}`} className="w-10 px-0" onClick={() => onChange(Math.max(0, value - 1))}>
        <IconMinus size={16} />
      </Button>
      <Input
        type="number"
        inputMode="numeric"
        min={0}
        aria-label={label}
        className="w-28 text-center text-lg font-semibold tabular"
        value={Number.isNaN(value) ? "" : value}
        // 0 or a whole number, no minimum: an empty box counts as 0.
        onChange={(e) => onChange(e.target.value === "" ? 0 : Number(e.target.value))}
      />
      <Button variant="secondary" aria-label={`Increase ${label}`} className="w-10 px-0" onClick={() => onChange((Number.isNaN(value) ? 0 : value) + 1)}>
        <IconPlus size={16} />
      </Button>
    </div>
  );
}

type Mode = "new" | "continue";

export default function NewPrintOrderPage() {
  const [mode, setMode] = useState<Mode>("new");
  return (
    <>
      <PageTitle title="New print order" subtitle="Answer each question; batch codes and lot numbers are generated by the system." />
      <div role="radiogroup" aria-label="Print order type" className="mb-4 flex flex-wrap gap-2">
        {(
          [
            ["new", "New batches"],
            ["continue", "Continue an existing batch"],
          ] as const
        ).map(([m, label]) => (
          <button
            key={m}
            type="button"
            role="radio"
            aria-checked={mode === m}
            onClick={() => setMode(m)}
            className={mode === m ? "inline-flex min-h-10 items-center rounded-full border-2 border-primary bg-primary px-4 font-semibold text-primary-foreground transition-colors duration-150" : "inline-flex min-h-10 items-center rounded-full border border-line-strong bg-surface px-4 text-foreground-2 transition-colors duration-150 hover:border-foreground hover:text-foreground"}
          >
            {label}
          </button>
        ))}
      </div>
      {mode === "new" ? <NewBatchesWizard /> : <ContinueBatchWizard />}
    </>
  );
}

function StepList({ steps, step }: { steps: readonly string[]; step: number }) {
  return (
    <ol className="mb-5 flex flex-wrap items-center gap-x-1 gap-y-2 text-xs" aria-label="Steps">
      {steps.map((s, i) => (
        <li key={s} aria-current={i === step ? "step" : undefined} className="flex items-center gap-1">
          <span
            className={cx(
              "inline-flex items-center gap-2 rounded-full border py-1 pl-1 pr-3 transition-colors duration-200",
              i === step ? "border-primary bg-primary font-semibold text-primary-foreground" : i < step ? "border-line-strong bg-surface text-foreground" : "border-line bg-transparent text-muted-foreground",
            )}
          >
            <span
              className={cx(
                "inline-flex h-5 w-5 items-center justify-center rounded-full text-[0.6875rem] font-bold",
                i === step ? "bg-primary-foreground text-primary" : i < step ? "bg-foreground text-background" : "bg-muted text-muted-foreground",
              )}
            >
              {i < step ? <IconCheck size={12} strokeWidth={2.5} /> : i + 1}
            </span>
            {s}
          </span>
          {i < steps.length - 1 && <span aria-hidden="true" className="h-px w-3 bg-line-strong" />}
        </li>
      ))}
    </ol>
  );
}

function NewBatchesWizard() {
  const { data, flavourName } = useSession();
  const router = useRouter();
  const [step, setStep] = useState(0);
  const [count, setCount] = useState(1);
  const [batches, setBatches] = useState<BatchInput[]>([newBatch()]);
  const [plan, setPlan] = useState<PrintOrderPlan | null>(null);
  const [offline, setOffline] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [created, setCreated] = useState<PrintOrder | null>(null);

  const flavours = (data?.flavours ?? []).filter((f) => f.active);
  const update = (i: number, patch: Partial<BatchInput>) => setBatches((bs) => bs.map((b, j) => (j === i ? { ...b, ...patch } : b)));

  async function loadPreview() {
    setBusy(true);
    setError(null);
    try {
      const r = await api<{ plan: PrintOrderPlan; device: { offline: boolean } }>("/api/print-orders", { body: { batches, preview: true } });
      setPlan(r.plan);
      setOffline(r.device.offline);
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  async function next() {
    setError(null);
    if (step === 0) {
      const n = Math.floor(count);
      if (!(n >= 1 && n <= 20)) return setError("Enter between 1 and 20 batches");
      setBatches((bs) => Array.from({ length: n }, (_, i) => bs[i] ?? newBatch()));
    }
    if (step === 1 && batches.some((b) => !b.flavour)) return setError("Choose a flavour for every batch");
    if (step === 4) await loadPreview();
    setStep((s) => Math.min(s + 1, STEPS.length - 1));
  }

  async function create() {
    setBusy(true);
    setError(null);
    try {
      const r = await api<{ printOrder: PrintOrder }>("/api/print-orders", { body: { batches } });
      setCreated(r.printOrder);
      notifyDataChanged();
      setStep(6);
    } catch (e) {
      setError(errorText(e));
      await loadPreview();
    } finally {
      setBusy(false);
    }
  }

  function restart() {
    setStep(0);
    setCount(1);
    setBatches([newBatch()]);
    setPlan(null);
    setCreated(null);
    setError(null);
  }

  const perBatch = (render: (b: BatchInput, i: number) => ReactNode) => (
    <div className="space-y-3">
      {batches.map((b, i) => (
        <div key={i} className="rounded-md border border-line bg-surface-2 p-3 sm:p-4">
          <div className="mb-2.5 text-sm font-bold text-foreground">
            Batch {i + 1}
            {b.flavour && <span className="font-normal text-muted-foreground"> · {flavourName(b.flavour)}</span>}
          </div>
          {render(b, i)}
        </div>
      ))}
    </div>
  );

  return (
    <>
      <StepList steps={STEPS} step={step} />

      <Card>
        {step === 0 && (
          <Field label="How many batches do you want to create?" hint="One batch = one flavour with one manufacture date; it gets its own random batch code.">
            <CountInput label="Number of batches" value={count} onChange={setCount} />
          </Field>
        )}

        {step === 1 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Which flavour?</h2>
            {perBatch((b, i) => (
              <div className="flex flex-wrap gap-2">
                {flavours.map((f) => (
                  <button
                    key={f.code}
                    type="button"
                    onClick={() => update(i, { flavour: f.code })}
                    aria-pressed={b.flavour === f.code}
                    className={b.flavour === f.code ? "inline-flex min-h-10 items-center gap-2 rounded-full border-2 border-primary bg-primary px-4 font-semibold text-primary-foreground transition-colors duration-150 [&_span]:text-primary-foreground/70" : "inline-flex min-h-10 items-center gap-2 rounded-full border border-line-strong bg-surface px-4 text-foreground-2 transition-colors duration-150 hover:border-foreground hover:text-foreground"}
                  >
                    {f.name} <span className="font-mono text-xs text-muted-foreground">{f.code}</span>
                  </button>
                ))}
              </div>
            ))}
          </>
        )}

        {step === 2 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Manufacture and expiry dates</h2>
            {perBatch((b, i) => (
              <div className="grid gap-3 sm:grid-cols-2">
                <Field label="Manufacture date">
                  <Input type="date" aria-label={`Batch ${i + 1} manufacture date`} value={b.mfgDate} onChange={(e) => update(i, { mfgDate: e.target.value })} />
                </Field>
                <Field label="Expiry date">
                  <Input type="date" aria-label={`Batch ${i + 1} expiry date`} value={b.expiryDate} onChange={(e) => update(i, { expiryDate: e.target.value })} />
                </Field>
              </div>
            ))}
          </>
        )}

        {step === 3 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">How many Cases (4 packs × 6 cans)?</h2>
            {perBatch((b, i) => (
              <CountInput label={`Batch ${i + 1} cases`} value={b.cases} onChange={(n) => update(i, { cases: n })} />
            ))}
          </>
        )}

        {step === 4 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">How many Trays (6 packs × 4 cans)?</h2>
            {perBatch((b, i) => (
              <CountInput label={`Batch ${i + 1} trays`} value={b.trays} onChange={(n) => update(i, { trays: n })} />
            ))}
          </>
        )}

        {step === 5 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Summary</h2>
            {offline && (
              <Notice tone="warn" className="mb-3">
                Device is offline: batch codes come from the reserved pool and the order will be saved unsynced (it can be printed and verified, but not dispatched until synced).
              </Notice>
            )}
            {plan ? (
              <>
                <Table head={["Batch", "Batch code", "Flavour", "Dates", "Cases", "Trays", "Lots (hex)", "Stickers"]}>
                  {plan.batches.map((b) => (
                    <tr key={b.index} data-testid={`summary-batch-${b.index + 1}`}>
                      <Td>{b.index + 1}</Td>
                      <Td>{b.batchCode ? <Code>{b.batchCode}</Code> : <span className="text-danger">none</span>}</Td>
                      <Td>{flavourName(b.flavour) || "—"}</Td>
                      <Td className="whitespace-nowrap text-xs">
                        {b.mfgDate} → {b.expiryDate}
                      </Td>
                      <Td>
                        {b.cases}
                        {b.caseRange && <div className="font-mono text-xs text-muted-foreground">{b.caseRange.join("–")}</div>}
                      </Td>
                      <Td>
                        {b.trays}
                        {b.trayRange && <div className="font-mono text-xs text-muted-foreground">{b.trayRange.join("–")}</div>}
                      </Td>
                      <Td>{b.lotRange ? <Code>{b.lotRange[0] === b.lotRange[1] ? b.lotRange[0] : b.lotRange.join("–")}</Code> : "—"}</Td>
                      <Td>
                        <span data-testid={`summary-stickers-${b.index + 1}`}>{b.stickerCount}</span>
                        <div className="text-xs text-muted-foreground">
                          {b.cases}×5 + {b.trays}×7
                        </div>
                      </Td>
                    </tr>
                  ))}
                  <tr className="bg-surface-2 font-semibold">
                    <Td>Total</Td>
                    <Td />
                    <Td />
                    <Td />
                    <Td>{plan.batches.reduce((s, b) => s + (b.cases || 0), 0)}</Td>
                    <Td>{plan.batches.reduce((s, b) => s + (b.trays || 0), 0)}</Td>
                    <Td>{plan.totalLots} lots</Td>
                    <Td>
                      <span data-testid="summary-total-stickers">{plan.totalStickers}</span>
                    </Td>
                  </tr>
                </Table>
                {plan.errors.length > 0 && (
                  <Notice tone="error" className="mt-3">
                    <ul className="list-disc pl-5">
                      {plan.errors.map((e, i) => (
                        <li key={i}>{e.message}</li>
                      ))}
                    </ul>
                  </Notice>
                )}
              </>
            ) : (
              <Loading>Calculating…</Loading>
            )}
          </>
        )}

        {step === 6 && created && (
          <div className="space-y-3">
            <Notice tone="ok">
              Print order created: {created.stickerCount} stickers for batch{created.batchCodes.length > 1 ? "es" : ""} {created.batchCodes.join(", ")}
              {!created.synced && " (offline — unsynced)"}.
            </Notice>
            <div className="flex flex-wrap gap-2">
              <Button onClick={() => router.push(`/print/${created.id}`)}>
                <IconPrinter size={17} />
                Open print view
              </Button>
              <Button variant="secondary" onClick={restart}>
                New print order
              </Button>
            </div>
            <GeneratedCodes printOrderId={created.id} />
          </div>
        )}

        {error && (
          <Notice tone="error" className="mt-3">
            {error}
          </Notice>
        )}

        {step < 6 && (
          <div className="mt-5 flex justify-between gap-2 border-t border-line pt-4">
            <Button variant="secondary" onClick={() => setStep((s) => Math.max(0, s - 1))} disabled={step === 0 || busy}>
              <IconArrowLeft size={17} />
              Back
            </Button>
            {step < 5 ? (
              <Button onClick={next} loading={busy}>
                Next
                <IconArrowRight size={17} />
              </Button>
            ) : (
              <Button onClick={create} loading={busy} disabled={!plan?.ok}>
                <IconPrinter size={17} />
                Create &amp; print
              </Button>
            )}
          </div>
        )}
      </Card>
    </>
  );
}

// ---------------------------------------------------------------- continue an existing batch
// The server owns the lot counter: the summary is an expected range, and the Print step shows only
// the range the server actually allocated. One request key per (batch, cases, trays), kept across
// retries so a repeated "Create & print" never allocates twice.

const CONTINUE_STEPS = ["Choose batch", "Cases & trays", "Summary", "Print"] as const;

interface ContinuableBatch {
  batchCode: string;
  flavour: string;
  flavourName: string;
  mfgDate: string;
  expiryDate: string;
  status: "ACTIVE" | "EXHAUSTED" | "COUNTER_INVALID" | "RECALLED";
  counter: BatchCounter;
  continuable: boolean;
  blockedReason: string | null;
}

interface ContinuePreview {
  ok: boolean;
  problem: { code: string; message: string } | null;
  batch: ContinuableBatch;
  device: { name: string; offline: boolean };
  totalLots: number;
  stickerCount: number;
  expectedFirstLotHex: string | null;
  expectedLastLotHex: string | null;
  remainingAfter: number | null;
  maxLotsPerOrder: number;
}

interface ContinueResult {
  replayed: boolean;
  printOrder: PrintOrder;
  batchCode: string;
  firstLotHex: string;
  lastLotHex: string;
  totalLots: number;
  stickerCount: number;
  counter: BatchCounter;
}

const STATUS_PILL: Record<ContinuableBatch["status"], { tone: "ok" | "warn" | "danger"; label: string }> = {
  ACTIVE: { tone: "ok", label: "Active" },
  EXHAUSTED: { tone: "warn", label: "Exhausted" },
  COUNTER_INVALID: { tone: "danger", label: "Counter invalid" },
  RECALLED: { tone: "danger", label: "Recalled" },
};

const fmt = (n: number | null) => (n === null ? "—" : n.toLocaleString("en-IN"));

function ContinueBatchWizard() {
  const router = useRouter();
  const list = useApi<{ maxLotsPerOrder: number; batches: ContinuableBatch[] }>("/api/print-orders/continue", { refreshOnChange: true });
  const [step, setStep] = useState(0);
  const [batchCode, setBatchCode] = useState<string | null>(null);
  const [cases, setCases] = useState(0);
  const [trays, setTrays] = useState(0);
  const [preview, setPreview] = useState<ContinuePreview | null>(null);
  const [key, setKey] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [created, setCreated] = useState<ContinueResult | null>(null);

  const selected = list.data?.batches.find((b) => b.batchCode === batchCode) ?? null;
  // A different request needs a different key; the same request keeps its key across retries.
  const choose = (code: string) => {
    setBatchCode(code);
    setKey(null);
  };
  const changeCount = (set: (n: number) => void) => (n: number) => {
    set(n);
    setKey(null);
  };

  async function loadPreview() {
    if (!batchCode) return;
    setBusy(true);
    setError(null);
    try {
      setPreview(await api<ContinuePreview>("/api/print-orders/continue", { body: { batchCode, cases, trays, preview: true } }));
    } catch (e) {
      setError(errorText(e));
    } finally {
      setBusy(false);
    }
  }

  async function next() {
    setError(null);
    if (step === 0 && !selected?.continuable) return setError("Choose a batch that can be continued");
    if (step === 1) {
      if (!Number.isInteger(cases) || !Number.isInteger(trays) || cases < 0 || trays < 0) return setError("Cases and trays must be 0 or a whole number");
      if (cases + trays < 1) return setError("Nothing to print: enter cases or trays (either one may be 0)");
      setPreview(null);
      await loadPreview();
    }
    setStep((s) => Math.min(s + 1, CONTINUE_STEPS.length - 1));
  }

  async function create() {
    if (!batchCode || busy) return;
    const idempotencyKey = key ?? crypto.randomUUID();
    setKey(idempotencyKey);
    setBusy(true);
    setError(null);
    try {
      const r = await api<ContinueResult>("/api/print-orders/continue", { body: { batchCode, cases, trays, idempotencyKey } });
      setCreated(r);
      notifyDataChanged();
      setStep(3);
    } catch (e) {
      // Keep the key: if the order was saved before the error reached us, retrying returns it.
      const message = errorText(e);
      await loadPreview();
      setError(message);
    } finally {
      setBusy(false);
    }
  }

  function restart() {
    setStep(0);
    setBatchCode(null);
    setCases(0);
    setTrays(0);
    setPreview(null);
    setKey(null);
    setCreated(null);
    setError(null);
  }

  return (
    <>
      <StepList steps={CONTINUE_STEPS} step={step} />
      <Card>
        {step === 0 && (
          <>
            <h2 className="mb-1 font-bold text-foreground">Which batch do you want to continue?</h2>
            <p className="mb-3 text-sm text-muted-foreground">
              New lots continue from the batch&apos;s next lot number and keep its flavour, manufacture and expiry dates. For different dates, create a new batch.
            </p>
            {list.error && <Notice tone="error">{list.error}</Notice>}
            {!list.data && !list.error && <Loading>Loading batches…</Loading>}
            {list.data && (
              <Table
                head={["", "Batch", "Flavour", "Mfg / Exp", "Last lot", "Next lot", "Used", "Remaining", "Status"]}
                empty={!list.data.batches.length ? <span className="text-muted-foreground">No batches yet. Create one with New batches.</span> : null}
              >
                {list.data.batches.map((b) => (
                  <tr
                    key={b.batchCode}
                    data-testid={`continue-batch-${b.batchCode}`}
                    // The whole row selects the batch, not only the small radio (keyboard users still use the radio).
                    onClick={() => b.continuable && batchCode !== b.batchCode && choose(b.batchCode)}
                    className={cx(b.continuable ? "cursor-pointer hover:bg-surface-2" : "opacity-60", batchCode === b.batchCode && "bg-muted")}
                  >
                    <Td>
                      <input type="radio" name="continue-batch" aria-label={`Batch ${b.batchCode}`} className="h-4 w-4 cursor-pointer" checked={batchCode === b.batchCode} disabled={!b.continuable} onChange={() => choose(b.batchCode)} />
                    </Td>
                    <Td>
                      <Code>{b.batchCode}</Code>
                    </Td>
                    <Td>{b.flavourName}</Td>
                    <Td className="whitespace-nowrap text-xs">
                      {b.mfgDate} / {b.expiryDate}
                    </Td>
                    <Td>{b.counter.lastLotHex ? <Code>{b.counter.lastLotHex}</Code> : "—"}</Td>
                    <Td>{b.counter.nextLotHex ? <Code>{b.counter.nextLotHex}</Code> : "—"}</Td>
                    <Td>{fmt(b.counter.lotsAllocated)}</Td>
                    <Td>{fmt(b.counter.remaining)}</Td>
                    <Td>
                      <Pill tone={STATUS_PILL[b.status].tone} dot className="uppercase">
                        {STATUS_PILL[b.status].label}
                      </Pill>
                      {b.blockedReason && <div className="mt-1 max-w-xs text-xs text-muted-foreground">{b.blockedReason}</div>}
                    </Td>
                  </tr>
                ))}
              </Table>
            )}
          </>
        )}

        {step === 1 && selected && (
          <div className="space-y-4">
            <h2 className="font-bold text-foreground">
              How many cases and trays for batch <Code>{selected.batchCode}</Code> · {selected.flavourName}?
            </h2>
            <Field label="Cases (4 packs × 6 cans)">
              <CountInput label="Cases" value={cases} onChange={changeCount(setCases)} />
            </Field>
            <Field label="Trays (6 packs × 4 cans)">
              <CountInput label="Trays" value={trays} onChange={changeCount(setTrays)} />
            </Field>
            <p className="text-sm text-muted-foreground">
              {fmt(selected.counter.remaining)} lots left in this batch (next <Code>{selected.counter.nextLotHex ?? "—"}</Code>, maximum <Code>1869F</Code>); at most{" "}
              {fmt(list.data?.maxLotsPerOrder ?? null)} lots per order.
            </p>
          </div>
        )}

        {step === 2 && (
          <>
            <h2 className="mb-3 font-bold text-foreground">Summary</h2>
            {preview ? (
              <>
                <Table head={["Batch", "Flavour", "Dates (from the batch)", "Cases", "Trays", "Expected lots (hex)", "Stickers", "Left after"]}>
                  <tr data-testid="continue-summary">
                    <Td>
                      <Code>{preview.batch.batchCode}</Code>
                    </Td>
                    <Td>{preview.batch.flavourName}</Td>
                    <Td className="whitespace-nowrap text-xs">
                      {preview.batch.mfgDate} → {preview.batch.expiryDate}
                    </Td>
                    <Td>{cases}</Td>
                    <Td>{trays}</Td>
                    <Td>
                      {preview.expectedFirstLotHex ? (
                        <Code>{preview.expectedFirstLotHex === preview.expectedLastLotHex ? preview.expectedFirstLotHex : `${preview.expectedFirstLotHex}–${preview.expectedLastLotHex}`}</Code>
                      ) : (
                        "—"
                      )}
                    </Td>
                    <Td>
                      {fmt(preview.stickerCount)}
                      <div className="text-xs text-muted-foreground">
                        {cases}×5 + {trays}×7
                      </div>
                    </Td>
                    <Td>{fmt(preview.remainingAfter)}</Td>
                  </tr>
                </Table>
                <p className="mt-3 text-xs text-muted-foreground">Expected range. The final range is confirmed by the server when you create the order.</p>
                {preview.problem && (
                  <Notice tone="error" className="mt-3">
                    {preview.problem.message}
                  </Notice>
                )}
              </>
            ) : (
              !error && <Loading>Calculating…</Loading>
            )}
          </>
        )}

        {step === 3 && created && (
          <div className="space-y-3">
            <Notice tone="ok">
              {created.replayed ? "This order was already created (the request was repeated), so it is shown again. " : "Print order created: "}
              {countLabel(created.stickerCount, "sticker")}, {countLabel(created.totalLots, "lot")} for batch {created.batchCode}:{" "}
              <Code>
                <span data-testid="continue-range">{lotRangeLabel(created.firstLotHex, created.lastLotHex)}</span>
              </Code>
              . {countLabel(created.counter.remaining, "lot")} left in the batch
              {created.counter.nextLotHex ? (
                <>
                  {" "}
                  (next <Code>{created.counter.nextLotHex}</Code>).
                </>
              ) : (
                "; the batch is now exhausted."
              )}
            </Notice>
            {!created.replayed && preview?.expectedFirstLotHex && preview.expectedFirstLotHex !== created.firstLotHex && (
              <Notice tone="info">
                Another order was allocated in the meantime, so your lots start at <Code>{created.firstLotHex}</Code> instead of the expected <Code>{preview.expectedFirstLotHex}</Code>.
              </Notice>
            )}
            <div className="flex flex-wrap gap-2">
              <Button onClick={() => router.push(`/print/${created.printOrder.id}`)}>
                <IconPrinter size={17} />
                Open print view
              </Button>
              <Button variant="secondary" onClick={restart}>
                New print order
              </Button>
            </div>
            <GeneratedCodes printOrderId={created.printOrder.id} />
          </div>
        )}

        {error && error !== preview?.problem?.message && (
          <Notice tone="error" className="mt-3">
            {error}
          </Notice>
        )}

        {step < 3 && (
          <div className="mt-5 flex justify-between gap-2 border-t border-line pt-4">
            <Button
              variant="secondary"
              onClick={() => {
                setError(null);
                setStep((s) => Math.max(0, s - 1));
              }}
              disabled={step === 0 || busy}
            >
              <IconArrowLeft size={17} />
              Back
            </Button>
            {step < 2 ? (
              <Button onClick={next} loading={busy} disabled={step === 0 && !selected?.continuable}>
                Next
                <IconArrowRight size={17} />
              </Button>
            ) : (
              <Button onClick={create} loading={busy} disabled={!preview?.ok}>
                <IconPrinter size={17} />
                Create &amp; print
              </Button>
            )}
          </div>
        )}
      </Card>
    </>
  );
}
